// genmap extracts coastlines around Japan from Natural Earth land polygons
// and writes them as Go source, so the map is embedded in the binary.
//
// Usage:
//
//	curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson
//	go run ./tools/genmap ne_50m_land.geojson > internal/japanmap/coast_gen.go
package main

import (
	"encoding/json"
	"fmt"
	"math"
	"os"
	"strings"
)

// Bounding box of the area to keep (longitude, latitude).
const (
	minLon, maxLon = 122.0, 150.0
	minLat, maxLat = 24.0, 46.5
	// Drop points closer than this to the previous one (degrees).
	// Keeps the generated file small without visibly changing the shape.
	minStep = 0.03
)

type geometry struct {
	Type        string          `json:"type"`
	Coordinates json.RawMessage `json:"coordinates"`
}

type featureCollection struct {
	Features []struct {
		Geometry geometry `json:"geometry"`
	} `json:"features"`
}

// ring is a sequence of (lon, lat) points.
type ring [][2]float64

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genmap <ne_50m_land.geojson>")
		os.Exit(2)
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	var fc featureCollection
	if err := json.Unmarshal(data, &fc); err != nil {
		fail(err)
	}

	var lines []ring
	for _, f := range fc.Features {
		var polys [][]ring
		switch f.Geometry.Type {
		case "Polygon":
			var p []ring
			if err := json.Unmarshal(f.Geometry.Coordinates, &p); err != nil {
				fail(err)
			}
			polys = [][]ring{p}
		case "MultiPolygon":
			if err := json.Unmarshal(f.Geometry.Coordinates, &polys); err != nil {
				fail(err)
			}
		}
		for _, p := range polys {
			for _, r := range p {
				for _, line := range clip(r) {
					lines = append(lines, simplify(line))
				}
			}
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/genmap; DO NOT EDIT.\n")
	b.WriteString("// Coastline data: Made with Natural Earth (public domain).\n\n")
	b.WriteString("package japanmap\n\n")
	b.WriteString("var coastlines = [][][2]float32{\n")
	total := 0
	for _, r := range lines {
		b.WriteString("\t{")
		for i, pt := range r {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "{%.2f, %.2f}", pt[0], pt[1])
		}
		b.WriteString("},\n")
		total += len(r)
	}
	b.WriteString("}\n")
	fmt.Print(b.String())
	fmt.Fprintf(os.Stderr, "genmap: %d lines, %d points\n", len(lines), total)
}

func inBox(pt [2]float64) bool {
	return pt[0] >= minLon && pt[0] <= maxLon && pt[1] >= minLat && pt[1] <= maxLat
}

// clip splits a ring into the runs of consecutive points inside the box.
// Only outlines are drawn, so open polylines are fine.
func clip(r ring) []ring {
	var lines []ring
	var cur ring
	for _, pt := range r {
		if inBox(pt) {
			cur = append(cur, pt)
			continue
		}
		if len(cur) > 1 {
			lines = append(lines, cur)
		}
		cur = nil
	}
	if len(cur) > 1 {
		lines = append(lines, cur)
	}
	return lines
}

func simplify(r ring) ring {
	out := ring{r[0]}
	for _, pt := range r[1:] {
		last := out[len(out)-1]
		if math.Hypot(pt[0]-last[0], pt[1]-last[1]) >= minStep {
			out = append(out, pt)
		}
	}
	// Keep the last point so closed rings stay closed.
	if out[len(out)-1] != r[len(r)-1] {
		out = append(out, r[len(r)-1])
	}
	return out
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genmap:", err)
	os.Exit(1)
}
